/**
 * 院区档案（虚构数据，S15）
 *
 * 契约与 `appt_campus` 表只有 `name / address / cover_url / sort / status`，
 * **没有联系电话、门诊时间、交通指引** → 这三类内容只能是前端常量（本切片不改接口与表）。
 *
 * 两条纪律：
 * 1. 按院区**名称**匹配，不按雪花 id —— 换库或重置 seed 后 id 会变，名称稳定；
 * 2. 未匹配的院区给通用兜底，不编造具体地铁线路与电话。
 */
export interface CampusProfile {
  /** 联系电话（虚构）；未匹配时为一句指引，不发号 */
  tel: string
  /** 门诊时间，逐行展示 */
  clinicHours: string[]
  /** 交通指引，逐行展示 */
  traffic: string[]
}

